// Regenerates items.js from the JSON that tools/itemdump writes:
//   node scripts/gen-items.js <items.json>
// Names the game leaves blank (skill capes, test items) fall back to the name
// already in items.js, then to the asset's file name.
const fs = require('node:fs');
const path = require('node:path');

const out = path.join(__dirname, '..', 'items.js');
const dump = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));

const previous = {};
try {
  const sandbox = {};
  new Function('self', fs.readFileSync(out, 'utf8'))(sandbox);
  Object.assign(previous, sandbox.DW_ITEMS);
} catch {}

// First matching folder under /Content/Gameplay/ wins.
const FOLDERS = [
  ['Equipment/Ammo/', 'Arrows'],
  ['Equipment/Body/', 'Body'],
  ['Equipment/Cape/', 'Capes'],
  ['Equipment/Head/', 'Helms'],
  ['Equipment/Legs/', 'Legs'],
  ['Held/Bow/', 'Bows'],
  ['UniqueWeapons/Shortbow/', 'Bows'],
  ['Held/Crossbow/', 'Crossbows'],
  ['Held/Staff/', 'Staves'],
  ['Held/Wand/', 'Staves'],
  ['Held/ScarabStaff/', 'Staves'],
  ['Held/AnimaOrb/', 'Staves'],
  ['UniqueWeapons/Staff/', 'Staves'],
  ['Held/Shield/', 'Shields'],
  ['Held/Farming/', 'Farming'],
  ['Held/FishingRod/Baits/', 'Fishing'],
  ['Held/FishingRod/', 'Tools'],
  ['Held/FishingNet/', 'Tools'],
  ['Held/Hatchet/', 'Tools'],
  ['Held/Pickaxe/', 'Tools'],
  ['Held/Shovel/', 'Tools'],
  ['Held/Bucket/', 'Tools'],
  ['Held/Torch/', 'Tools'],
  ['Held/Thrown/', 'Throwables'],
  ['Held/StatusEffect_Test/', 'Test'],
  ['Held/', 'Melee Weapons'],
  ['Items/Consumables/Food/', 'Food'],
  ['Items/Consumables/Magic/', 'Potions'],
  ['Items/Potions/', 'Potions'],
  ['Items/Consumables/Tomes/', 'Tomes'],
  ['Items/Tomes/', 'Tomes'],
  ['Items/Fishes/', 'Fish'],
  ['Items/Resources/Fish/', 'Fish'],
  ['Items/Quest/', 'Quest'],
  ['Items/Journaltems/', 'Quest'],
  ['Items/Resources/Key/', 'Keys'],
  ['Items/Resources/Herb/', 'Herbs'],
  ['Items/Resources/Wood/', 'Woodcutting'],
  ['Items/Resources/Gem/', 'Gems'],
  ['Items/Packs/', 'Packs'],
];

function category(item, name) {
  const p = item.path.replace(/^.*?\/Content\/Gameplay\//, '');
  if (/\/Jewe?l+e?ry\//.test(p)) return /amulet|necklace|pendant/i.test(name) ? 'Amulets' : 'Rings';
  if (/Consumables_(Food|Drink)/.test(item.class)) return 'Food';
  if (/Consumables_Potion/.test(item.class)) return 'Potions';
  if (/SkillTome/.test(item.class)) return 'Tomes';
  if (item.class === 'MagicAmmoData' || (p.includes('Resources/Magic/') && / Rune$/.test(name))) return 'Runes';
  for (const [folder, cat] of FOLDERS) if (p.includes(folder)) return cat;
  if (/\bOre\b/.test(name)) return 'Ores';
  if (/\bBar\b/.test(name)) return 'Bars';
  return 'Basic Item';
}

function fileName(item) {
  return path.basename(item.path, '.uasset').replace(/^ITEM_/, '').replace(/_/g, ' ')
    .replace(/([a-z])([A-Z])/g, '$1 $2');
}

const entries = dump.map((item) => {
  const name = item.name || (previous[item.id] && previous[item.id][0]) || fileName(item);
  return [item.id, name, category(item, name)];
});
entries.sort((a, b) => a[1].localeCompare(b[1], 'en') || a[0].localeCompare(b[0]));

const lines = entries.map(([id, name, cat]) => `  ${JSON.stringify(id)}: [${JSON.stringify(name)}, ${JSON.stringify(cat)}],`);
fs.writeFileSync(out, [
  '// Item names by ItemData ID, for display only. Generated by',
  '// scripts/gen-items.js from the game\'s own data files (tools/itemdump);',
  '// regenerate after a game update.',
  'self.DW_ITEMS = {',
  ...lines,
  '};',
  '',
].join('\n'));
console.log(`Wrote ${entries.length} items to items.js`);
