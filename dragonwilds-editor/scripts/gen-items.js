function category(item, name) {
  const p = item.path.replace(/^.*?\/Content\/Gameplay\//, '');
  if (/\/Jewe?l+e?ry\//.test(p)) return /amulet|necklace|pendant/i.test(name) ? 'Amulets' : 'Rings';
  if (/Consumables_(Food|Drink)/.test(item.class)) return 'Food';
  if (/Consumables_Potion/.test(item.class)) return 'Potions';
  if (/SkillTome/.test(item.class)) return 'Tomes';
  if (item.class === 'MagicAmmoData' || (p.includes('Resources/Magic/') && / Rune$/.test(name))) return 'Runes';
  for (const [folder, cat] of FOLDERS) if (p.includes(folder)) return cat;
  if (/\bOre\b/.test(name)) return 'Ores';
  if (/\bBar\b/.test(name)) return 'Bars';
  return 'Basic Item';
}

function prettify(file, prefix) {
  return path.basename(file, '.uasset').replace(prefix, '').replace(/_/g, ' ')
    .replace(/([a-z])([A-Z])/g, '$1 $2');
}

// items.js
const itemDump = Array.isArray(dump) ? dump : dump.items;
const items = itemDump.map((item) => {
  const name = item.name || (previous[item.id] && previous[item.id][0]) || prettify(item.path, /^ITEM_/);
  return { ...item, name, category: category(item, name) };
});
items.sort((a, b) => a.name.localeCompare(b.name, 'en') || a.id.localeCompare(b.id));
write('items.js', 'DW_ITEMS', [
  '// Item names by ItemData ID, for display only. Generated by',
  '// scripts/gen-items.js from the game\'s own data files (tools/itemdump);',
  '// regenerate after a game update.',
], items.map((i) => [i.id, [i.name, i.category]]));

// recipes.js. A recipe references the item it makes and its ingredients, in
// no fixed order; the output is the item whose asset name shares the most
// words with the recipe's (RECIPE_Armour_T0_Cape_Fire -> ITEM_Cape_Fire).
if (!Array.isArray(dump)) {
  const byAsset = new Map(items.map((i) => [path.basename(i.path, '.uasset').toLowerCase(), i]));
  const NOISE = new Set(['recipe', 'item', 'armour', 'weapon', 'resources', 'resource', 'consumable',
    't0', 't1', 't2', 't3', 't4', 't5', 't6', 't7', 't8', 't9']);
  const words = (s) => s.replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase().split(/_+/).filter((w) => w && !NOISE.has(w));
  const output = (recipe) => {
    const mine = new Set(words(path.basename(recipe.path, '.uasset')));
    let best = null;
    let bestScore = 0;
    for (const ref of recipe.items) {
      const theirs = words(ref);
      const shared = theirs.filter((w) => mine.has(w)).length;
      const score = shared / (mine.size + theirs.length - shared);
      if (score > bestScore) [best, bestScore] = [ref, score];
    }
    return best && byAsset.get(best.toLowerCase());
  };
  const recipes = dump.recipes.map((r) => {
    const file = path.basename(r.path, '.uasset');
    const made = output(r);
    // The asset name tells apart recipes for the same item (five make Bronze Bar).
    if (/^RECIPE_Journal_/i.test(file)) return [r.id, ['Journal: ' + prettify(file, /^RECIPE_Journal_/i), 'Journal', null, file]];
    if (/^RECIPE_Vendor_/i.test(file)) return [r.id, ['Vendor: ' + prettify(file, /^RECIPE_Vendor_/i), 'Vendor', null, file]];
    if (made) return [r.id, [made.name, made.category, made.id, file]];
    return [r.id, [prettify(file, /^RECIPE_/i), 'Other', null, file]];
  });
  recipes.sort((a, b) => a[1][0].localeCompare(b[1][0], 'en') || a[0].localeCompare(b[0]));
  write('recipes.js', 'DW_RECIPES', [
    '// Recipes by the ID that Progress.RecipesUnlocked holds, as',
    '// [name, category, ID of the item it makes or null, asset name]. Generated by',
    '// scripts/gen-items.js from the game\'s own data files (tools/itemdump).',
  ], recipes);
}

function write(file, global, header, entries) {
  const lines = entries.map(([id, value]) => `  ${JSON.stringify(id)}: ${JSON.stringify(value).replace(/","|",|,"/g, (m) => m.replace(',', ', '))},`);
  fs.writeFileSync(path.join(__dirname, '..', file), [...header, `self.${global} = {`, ...lines, '};', ''].join('\n'));
  console.log(`Wrote ${entries.length} entries to ${file}`);
}
