function shadesOf(pal: string): Shades {
  return PALETTE[pal] ?? ['#444444', '#888888', '#cccccc'];
}

function paint(name: string, tpl: string, pal: string): SpriteDef {
  const rows = T[tpl];
  if (!rows) throw new Error(`no template "${tpl}" for ${name}`);
  const [d, m, l] = shadesOf(pal);
  const colours: Record<string, string> = { ...FIXED, '1': d, '2': m, '3': l, X: '#b02a2a', q: '#a89870' };
  const W = 16;
  const H = 16;
  const grid: (string | null)[] = Array.from({ length: W * H }, () => null);
  const h = rows.length;
  const w = Math.max(...rows.map((r) => r.length));
  if (w > W || h > H) throw new Error(`template "${tpl}" is ${w}×${h}, more than 16×16`);
  const ox = Math.floor((W - w) / 2);
  const oy = Math.floor((H - h) / 2);
  rows.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) {
      const ch = row[i]!;
      if (ch === '.') continue;
      const c = colours[ch];
      if (!c) throw new Error(`template "${tpl}": no colour for "${ch}"`);
      grid[(oy + j) * W + ox + i] = c;
    }
  });
  return { name, w: W, h: H, px: outline(grid, W, H) };
}

/** A one-pixel dark outline around every opaque shape. */
function outline(px: (string | null)[], w: number, h: number): (string | null)[] {
  const out = [...px];
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (px[y * w + x]) continue;
      const near = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => {
        const nx = x + dx!;
        const ny = y + dy!;
        return nx >= 0 && ny >= 0 && nx < w && ny < h && px[ny * w + nx];
      });
      if (near) out[y * w + x] = OUTLINE;
    }
  }
  return out;
}

export function allIcons(): string[] {
  const set = new Set<string>();
  for (const it of ITEMS) set.add(it.icon);
  for (const m of MONSTERS) set.add(m.icon);
  for (const a of AREAS) set.add(a.icon);
  for (const a of ACTIONS) set.add(a.icon);
  for (const e of SHOP) set.add(e.icon);
  for (const p of PETS) set.add(p.icon);
  for (const p of PRAYERS) set.add(p.icon);
  for (const s of SPELLS) set.add(s.icon);
  for (const b of BUILDINGS) set.add(b.icon);
  for (const s of SKILL_LIST) set.add(SKILL_ICON[s.id]!);
  for (const k of Object.keys(UI)) set.add(`ui.${k}`);
  // Ranch animals are drawn as quads, cows to drakes.
  for (const pal of ['worm', 'white', 'brown', 'wool', 'pink', 'fox', 'green']) set.add(`quad.${pal}`);
  set.add('beast.wool');
  return [...set].sort();
}

export function buildSprites(): SpriteDef[] {
  return allIcons().map((icon) => {
    const dot = icon.indexOf('.');
    const tpl = icon.slice(0, dot);
    const pal = icon.slice(dot + 1);
    if (tpl === 'ui') {
      const [t, p] = UI[pal] ?? ['star', 'gold'];
      return paint(icon, t, p);
    }
    return paint(icon, tpl, pal);
  });
}
